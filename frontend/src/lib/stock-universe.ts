/**
 * Filter stocks based on user query.
 * Matches:
 * 1. Exact symbol prefix (e.g. "REL" -> "RELIANCE")
 * 2. Symbol substring
 * 3. Company name match
 * 4. Industry match
 */
export function searchStockUniverse(query: string, limit: number = 8): StockUniverseItem[] {
  const q = query.trim().toUpperCase();
  if (!q) {
    // Return popular/trending stocks when query is empty
    return STOCK_UNIVERSE.filter((s) => s.isPopular).slice(0, limit);
  }

  // 1. Exact symbol prefix matches (highest priority)
  const prefixMatches = STOCK_UNIVERSE.filter((s) => s.symbol.startsWith(q));

  // 2. Symbol substring matches (excluding prefix)
  const symbolSubMatches = STOCK_UNIVERSE.filter(
    (s) => !s.symbol.startsWith(q) && s.symbol.includes(q)
  );

  // 3. Name or industry matches
  const nameOrIndustryMatches = STOCK_UNIVERSE.filter((s) => {
    if (s.symbol.includes(q)) return false;
    const nameUpper = s.name.toUpperCase();
    const indUpper = s.industry.toUpperCase();
    return nameUpper.includes(q) || indUpper.includes(q);
  });

  const combined = [...prefixMatches, ...symbolSubMatches, ...nameOrIndustryMatches];
  return combined.slice(0, limit);
}
